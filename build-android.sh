#!/bin/bash
set -eu

cd /home/user/workspace

export PYTHON3_EXEC="$( which python3 )"
# stdlib sysconfig, not distutils.sysconfig -- distutils was removed in Python 3.12,
# which is the default on Ubuntu 24.04. Both return identical values for these keys.
export PYTHON3_LIBRARY="$( ${PYTHON3_EXEC} -c 'import os.path, sysconfig; print(os.path.realpath(os.path.join(sysconfig.get_config_var("LIBPL"), sysconfig.get_config_var("LDLIBRARY"))))' )"
export PYTHON3_INCLUDE_DIR="$( ${PYTHON3_EXEC} -c 'import sysconfig; print(sysconfig.get_config_var("INCLUDEPY"))' )"
export CMAKE_PREFIX_PATH="/usr/share/eigen3/cmake:${PWD}/install:${CMAKE_PREFIX_PATH:-}"

# DT_RUNPATH=$ORIGIN on every shared library, so a library's DT_NEEDED also resolve from
# the folder it was loaded from (e.g. libraries unpacked outside the app's native library
# dir). lld writes DT_RUNPATH (--enable-new-dtags is its default).
#  - CMAKE_INSTALL_RPATH can't do this: CMake's Platform/Android.cmake empties
#    CMAKE_SHARED_LIBRARY_RUNTIME_C_FLAG, so CMake never emits an rpath on Android.
#  - A -DCMAKE_SHARED_LINKER_FLAGS on the colcon line misses the vendor packages
#    (console_bridge_vendor, orocos_kdl_vendor, tinyxml2_vendor), which configure the
#    upstream project as a separate CMake build and forward only the toolchain file and
#    compile flags. LDFLAGS is no help either: the NDK's (legacy, default) toolchain file
#    sets CMAKE_{SHARED,MODULE}_LINKER_FLAGS itself, to its own flags plus the cache value.
# So wrap the NDK toolchain file and append the flag to those variables after it has set
# them. Every sub-build receives the wrapper as its CMAKE_TOOLCHAIN_FILE. The guard keeps
# the flag single when the file is included more than once or a cache already has it.
# The NDK's own linker flags (16 KB pages, build id, ...) are kept.
NDK_TOOLCHAIN_FILE="${CMAKE_TOOLCHAIN_FILE}"
CMAKE_TOOLCHAIN_FILE="${PWD}/android-runpath.toolchain.cmake"
cat > "${CMAKE_TOOLCHAIN_FILE}" <<TOOLCHAIN
# Generated by build-android.sh: the NDK toolchain file plus DT_RUNPATH=\$ORIGIN.
include("${NDK_TOOLCHAIN_FILE}")
foreach(_runpath_var CMAKE_SHARED_LINKER_FLAGS CMAKE_MODULE_LINKER_FLAGS)
  string(FIND "\${\${_runpath_var}}" "-Wl,-rpath,\\\$ORIGIN" _runpath_found)
  if(_runpath_found EQUAL -1)
    string(APPEND \${_runpath_var} " -Wl,-rpath,\\\$ORIGIN")
  endif()
endforeach()
TOOLCHAIN

colcon build \
    --packages-ignore rcl_logging_log4cxx rcl_logging_spdlog rosidl_generator_py rclandroid ros2_talker_android ros2_listener_android performance_test_fixture osrf_testing_tools_cpp google_benchmark_vendor launch_testing_ament_cmake \
    tf2_kdl tf2_eigen tf2_eigen_kdl tf2_py python_orocos_kdl_vendor tf2_bullet \
    zenoh_security_tools test_rmw_zenoh_cpp \
    lttngpy rosidl_buffer_py rmw_test_fixture_implementation \
    --cmake-args \
    -DPython3_EXECUTABLE=${PYTHON3_EXEC} \
    -DPython3_LIBRARY=${PYTHON3_LIBRARY} \
    -DPython3_INCLUDE_DIR=${PYTHON3_INCLUDE_DIR} \
    -DCMAKE_TOOLCHAIN_FILE=${CMAKE_TOOLCHAIN_FILE} \
    -DANDROID=ON \
    -DANDROID_FUNCTION_LEVEL_LINKING=OFF \
    -DANDROID_PLATFORM=${ANDROID_TARGET} \
    -DANDROID_NATIVE_API_LEVEL=${ANDROID_TARGET} \
    -DANDROID_TOOLCHAIN_NAME=${ANDROID_TOOLCHAIN_NAME} \
    -DANDROID_STL=c++_shared \
    -DANDROID_ABI=${ANDROID_ABI} \
    -DANDROID_NDK=${ANDROID_NDK} \
    -DTHIRDPARTY=ON  \
    -DCOMPILE_EXAMPLES=OFF \
    -DCMAKE_FIND_ROOT_PATH="${PWD}/install" \
    -DBUILD_TESTING=OFF \
    -DRCL_LOGGING_IMPLEMENTATION=rcl_logging_noop \
    -DEIGEN3_INCLUDE_DIR=/usr/include/eigen3 \
    -DEigen3_DIR=/usr/share/eigen3/cmake \
    -Dnlohmann_json_DIR=/opt/nlohmann_json \
    -DZENOHC_CUSTOM_TARGET=${ANDROID_TOOLCHAIN_NAME}

## copy libc++_shared.so
# cp /opt/android/android-ndk-r23b/sources/cxx-stl/llvm-libc++/libs/${ANDROID_ABI}/libc++_shared.so /home/user/workspace
cp ${ANDROID_NDK}/toolchains/llvm/prebuilt/linux-x86_64/sysroot/usr/lib/aarch64-linux-android/libc++_shared.so /home/user/workspace
